#!/usr/bin/env python3
"""Census build: a counting hook on every recompiled function in an address range (the XDK Direct3D block), to find
the game's Direct3D functions by how often they run per presented frame.

  python3 nx/tools/d3d_census.py [--lo 0x82E00000] [--hi 0x82E50000] [--swap 0x82E28A30]
      -> nx/out/census/mgsv_d3d_census.cpp

Build the PC test build with -DMGSV_EXTRA_SOURCES=<that file> and run it with MGSV_CENSUS_FILE=<path>: every 5 s the
counts of the last interval are appended there as "sub_XXXXXXXX calls per_swap", sorted, with the swap count (calls
of --swap, the function that calls VdSwap). Each hook only bumps a relaxed atomic counter and calls the original.
"""
import argparse
import glob
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
GEN = os.path.join(ROOT, 'nx', 'generated', 'default')
OUT = os.path.join(ROOT, 'nx', 'out', 'census')
DEF = re.compile(r'^DEFINE_REX_FUNC\(sub_([0-9A-F]{8})\) \{$', re.M)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--lo', type=lambda s: int(s, 0), default=0x82E00000)
    ap.add_argument('--hi', type=lambda s: int(s, 0), default=0x82E50000)
    ap.add_argument('--swap', type=lambda s: int(s, 0), default=0x82E28A30)
    a = ap.parse_args()

    funcs = set()
    for path in glob.glob(os.path.join(GEN, '*_recomp.*.cpp')):
        for m in DEF.finditer(open(path, errors='replace').read()):
            addr = int(m.group(1), 16)
            if a.lo <= addr < a.hi:
                funcs.add(addr)
    funcs = sorted(funcs)
    if a.swap not in funcs:
        raise SystemExit(f'--swap {a.swap:08X} is not a function in the range')
    os.makedirs(OUT, exist_ok=True)
    out = os.path.join(OUT, 'mgsv_d3d_census.cpp')
    swap_index = funcs.index(a.swap)
    with open(out, 'w') as f:
        f.write('// Generated by nx/tools/d3d_census.py - counting hooks for the Direct3D census (PC test build only).\n')
        f.write('#include <algorithm>\n#include <atomic>\n#include <chrono>\n#include <cstdint>\n#include <cstdio>\n')
        f.write('#include <cstdlib>\n#include <thread>\n#include <vector>\n\n#include <rex/hook.h>\n#include <rex/ppc.h>\n\n')
        f.write(f'static constexpr unsigned kCount = {len(funcs)};\n')
        f.write('static constexpr uint32_t kAddr[kCount] = {\n')
        for i in range(0, len(funcs), 8):
            f.write('  ' + ', '.join(f'0x{x:08X}u' for x in funcs[i:i + 8]) + ',\n')
        f.write('};\n')
        f.write('static std::atomic<uint64_t> g_calls[kCount];\n\n')
        for i, addr in enumerate(funcs):
            f.write(f'REX_EXTERN(__imp__sub_{addr:08X});\n')
            f.write(f'REX_HOOK_RAW(sub_{addr:08X}) {{ g_calls[{i}].fetch_add(1, std::memory_order_relaxed); '
                    f'__imp__sub_{addr:08X}(ctx, base); }}\n')
        f.write(f'''
namespace {{
struct CensusReporter {{
  CensusReporter() {{
    const char* path = std::getenv("MGSV_CENSUS_FILE");
    if (!path || !*path) return;
    std::thread([path] {{
      std::vector<uint64_t> last(kCount, 0);
      for (unsigned interval = 0;; ++interval) {{
        std::this_thread::sleep_for(std::chrono::seconds(5));
        std::vector<std::pair<uint64_t, unsigned>> rows;
        std::vector<uint64_t> now(kCount);
        for (unsigned i = 0; i < kCount; ++i) now[i] = g_calls[i].load(std::memory_order_relaxed);
        const uint64_t swaps = now[{swap_index}] - last[{swap_index}];
        for (unsigned i = 0; i < kCount; ++i)
          if (now[i] != last[i]) rows.push_back({{now[i] - last[i], i}});
        std::sort(rows.rbegin(), rows.rend());
        if (FILE* f = std::fopen(path, "a")) {{
          std::fprintf(f, "==== interval %u: %llu swaps\\n", interval, (unsigned long long)swaps);
          unsigned shown = 0;
          for (auto& [n, i] : rows) {{
            if (++shown > 400) break;
            std::fprintf(f, "sub_%08X %llu %.2f\\n", kAddr[i], (unsigned long long)n,
                         swaps ? double(n) / double(swaps) : 0.0);
          }}
          std::fclose(f);
        }}
        last = now;
      }}
    }}).detach();
  }}
}} g_census_reporter;
}}  // namespace
''')
    print(f'{len(funcs)} functions in {a.lo:08X}..{a.hi:08X} -> {out}')


if __name__ == '__main__':
    main()
